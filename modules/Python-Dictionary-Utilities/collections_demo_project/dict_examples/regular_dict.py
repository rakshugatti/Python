# Example 1: Student Marks Management System
def student_marks():
    marks = {
        "Alice": 85,
        "Bob": 90,
        "Charlie": 78
    }

    print("\nStudent Marks:")
    for student, mark in marks.items():
        print(student, ":", mark)


# Example 2: Online Store Product Prices
def product_prices():
    products = {
        "Laptop": 70000,
        "Mouse": 500,
        "Keyboard": 1500
    }

    print("\nProduct Prices:")
    for product, price in products.items():
        print(product, ":", price)